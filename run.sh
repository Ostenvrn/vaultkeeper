#!/bin/bash
# ============================================
# run.sh — сканирование системы + коммит снапшота
# Использование:
#   На хосте:                        ./run.sh
#   В контейнере с примонтированным: docker run -v /:/host ...
# ============================================

# ============================================
# КОММИТ: фикс: убран хардкод пути + авто-определение HOST_ROOT
# Причина: старый run.sh делал cd /home/osten/devops/vaultkeeper
#          — падал в контейнере. Плюс HOST_ROOT надо было задавать вручную.
# Решение:
#   - cd в директорию скрипта (dirname $0)
#   - если /host смонтирован и HOST_ROOT не задан — ставим HOST_ROOT=/host
# ============================================

set -e

# Переходим в директорию скрипта (работает и в контейнере, и на хосте)
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

# Авто-определение режима:
# 1. Если HOST_ROOT задан вручную — используем его
# 2. Если /host существует и не пусто — значит мы в контейнере с -v /:/host
# 3. Иначе — работаем на хосте
if [ -z "${HOST_ROOT:-}" ] && [ -d "/host/etc" ]; then
    export HOST_ROOT="/host"
fi

echo "📂 Рабочая директория: $SCRIPT_DIR"
if [ -n "${HOST_ROOT:-}" ]; then
    echo "🐳 Режим контейнера: сканируем $HOST_ROOT (хост)"
else
    echo "🖥️  Режим хоста: сканируем локальную систему"
fi

# Запускаем сканер
echo ""
echo "🔍 Запуск сканера..."
python3 src/scanner.py

# Git-коммит: только если git доступен
if command -v git &> /dev/null; then
    echo ""
    echo "📸 Коммит снапшота..."
    python3 src/git_operator.py || echo "⚠️ Коммит не удался, продолжаем"
else
    echo ""
    echo "ℹ️ git не найден, пропускаю коммит"
fi

echo ""
echo "✅ Готово"
